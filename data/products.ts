function stock(
  colors: string[],
  sizes: string[],
  missing: Record<string, string[]> = {},
) {
  return Object.fromEntries(
    colors.map((color) => [
      color,
      sizes.filter((size) => !(missing[color] ?? []).includes(size)),
    ]),
  );
}

